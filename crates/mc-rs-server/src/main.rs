#[tokio::main]
async fn main() {
    // La config pilote la section [logging] — on la charge AVANT l'init de
    // tracing. ServerConfig::load est silencieux et renvoie des notes à
    // émettre une fois le logger prêt.
    let (config, bootstrap_notes) = ServerConfig::load("server.toml");

    // Broadcast channel logs → webui (créé AVANT logging::init pour que les
    // tout premiers logs du boot soient captés). Un receiver est consommé par
    // chaque client WebSocket `/ws/logs`.
    let (webui_log_tx, _) = tokio::sync::broadcast::channel::<mc_rs_webui::LogLine>(1024);
    let webui_log_tx_for_logging = config.webui.enabled.then(|| webui_log_tx.clone());

    // Le guard doit rester vivant toute la durée du process (flush au Drop).
    let _log_guard = crate::logging::init(&config.logging, webui_log_tx_for_logging);
    crate::logging::install_panic_hook(config.logging.directory.clone());
    crate::watchdog::start(config.logging.directory.clone());

    info!("MC-RS Server starting...");
    bootstrap_notes.flush();
    let world_dir = std::path::Path::new("worlds").join(&config.world.name);
    let world_seed = config.resolve_world_seed(&world_dir);
    let conn_config = config.connection_config(world_seed);
    let mut server_state = ServerState::load(
        config.server.motd.clone(),
        config.world.name.clone(),
        world_seed,
        config.server.max_players,
    );
    let plugin_manager = Arc::new(Mutex::new(PluginManager::load_from_dir(
        std::path::Path::new("plugins"),
    )));
    let mut command_system = build_command_system();
    if let Ok(mut manager) = plugin_manager.lock() {
        manager.register_permissions(&mut command_system.permissions);
        manager.enable_plugins(PluginLoadOrder::Startup, &mut command_system);
    } else {
        warn!("Plugin manager lock is poisoned during startup; plugins are disabled.");
    }

    // Generate server keypair (reused across all connections)
    let server_keypair = Arc::new(ServerKeyPair::generate());
    info!("Server EC keypair generated");

    // Generate server GUID
    let server_guid: i64 = rand::random();

    // Build MOTD
    let motd = Motd {
        name: config.server.motd.clone(),
        protocol_version: 975,
        version_string: "1.26.20".to_string(),
        online_players: 0,
        max_players: config.server.max_players,
        server_guid,
        world_name: config.world.name.clone(),
        gamemode: config.gameplay.gamemode_display().to_string(),
    };

    // Bind RakNet server
    let addr: SocketAddr = format!("0.0.0.0:{}", config.server.port).parse().unwrap();
    let mut raknet = match RakNetServer::bind(addr, motd, server_guid).await {
        Ok(s) => s,
        Err(e) => {
            error!("Failed to bind: {}", e);
            return;
        }
    };

    info!("Server listening on {} — waiting for connections", addr);

    // Connection tracking
    let mut connections: HashMap<SocketAddr, Connection> = HashMap::new();
    let mut peers: HashMap<SocketAddr, mc_rs_raknet::RakNetPeer> = HashMap::new();
    let mut registry = PlayerRegistry::new();
    let mut item_entities = ItemEntityManager::new();
    let mut mob_entities = MobEntityManager::new();
    let mut furnace_manager = crate::furnace::FurnaceManager::new();
    let mut chest_manager = crate::chest_storage::ChestManager::new();
    let mut sign_manager = crate::sign_storage::SignManager::new();
    let mut crafting_manager = crate::crafting::CraftingManager::default();
    let (sh, sl, fu) = crate::recipes_vanilla::register_all(&mut crafting_manager);
    tracing::info!(
        "Loaded vanilla recipes: {} shaped + {} shapeless + {} furnace",
        sh,
        sl,
        fu
    );
    let crafting_manager = crafting_manager;
    // Static recipe DB — utilisé par InventoryManager::try_match_recipe
    // sans avoir besoin de passer la référence à chaque appel.
    let _ = crate::crafting::RECIPE_DB.set(crafting_manager.clone());
    // Passive entities (TNT / FallingBlock / XPOrb) — spawned via commands or events.
    let _passive_entities = crate::passive_entities::PassiveEntityManager::new();
    // Event manager partagé (tous les Connection le clonent).
    let event_manager: Arc<std::sync::Mutex<crate::event::EventManager>> =
        Arc::new(std::sync::Mutex::new(crate::event::EventManager::new()));

    // Broadcast channel events webui — créé tôt pour que les event handlers
    // puissent le capturer dans leurs closures avant que la main loop ne parte.
    let (webui_event_tx, _) = tokio::sync::broadcast::channel::<mc_rs_webui::WebEvent>(256);

    // Webui event bridge : priority Monitor (read-only observer, dernier dans la
    // chaîne PMMP). Converti chaque event serveur en WebEvent et push dans le
    // broadcast. `try_send` via broadcast : si aucun client, le send est no-op.
    if config.webui.enabled {
        use crate::event::player::{
            PlayerChatEvent, PlayerDeathEvent, PlayerGameModeChangeEvent, PlayerJoinEvent,
            PlayerQuitEvent,
        };
        use crate::event::EventPriority;
        if let Ok(mut mgr) = event_manager.lock() {
            let tx = webui_event_tx.clone();
            mgr.register(
                EventPriority::Monitor,
                true,
                move |ev: &mut PlayerJoinEvent| {
                    let _ = tx.send(mc_rs_webui::WebEvent::PlayerJoin {
                        name: ev.display_name.clone(),
                        addr: ev.player_addr.to_string(),
                        xuid: ev.xuid.clone(),
                    });
                },
            );
            let tx = webui_event_tx.clone();
            mgr.register(
                EventPriority::Monitor,
                true,
                move |ev: &mut PlayerQuitEvent| {
                    let _ = tx.send(mc_rs_webui::WebEvent::PlayerQuit {
                        name: ev.display_name.clone(),
                        addr: ev.player_addr.to_string(),
                    });
                },
            );
            let tx = webui_event_tx.clone();
            mgr.register(
                EventPriority::Monitor,
                true,
                move |ev: &mut PlayerChatEvent| {
                    let _ = tx.send(mc_rs_webui::WebEvent::PlayerChat {
                        name: ev.sender_name.clone(),
                        message: ev.message.clone(),
                    });
                },
            );
            let tx = webui_event_tx.clone();
            mgr.register(
                EventPriority::Monitor,
                true,
                move |ev: &mut PlayerDeathEvent| {
                    let _ = tx.send(mc_rs_webui::WebEvent::PlayerDeath {
                        name: ev.death_message.clone(),
                        cause: "unknown".to_string(),
                    });
                },
            );
            let tx = webui_event_tx.clone();
            mgr.register(
                EventPriority::Monitor,
                true,
                move |ev: &mut PlayerGameModeChangeEvent| {
                    let _ = tx.send(mc_rs_webui::WebEvent::PlayerGamemodeChange {
                        name: ev.player_addr.to_string(),
                        new_mode: ev.new_gamemode,
                    });
                },
            );
        }
    }
    let mut world_state = WorldState::new(
        config.gameplay.do_daylight_cycle,
        config.gameplay.do_weather_cycle,
    );

    // Restore level.dat metadata si présent (sinon reste sur défauts).
    if let Some(level) = crate::level_dat::LevelData::load(&world_dir) {
        world_state.time = level.time;
        world_state.is_raining = level.is_raining;
        world_state.is_thundering = level.is_thundering;
        tracing::info!(
            "Restored level.dat : time={}, rain={}, thunder={}",
            level.time,
            level.is_raining,
            level.is_thundering
        );
    }

    // World chunk cache with LevelDB persistence
    let chunk_cache = std::sync::Arc::new(std::sync::Mutex::new(ChunkCache::new(
        &world_dir,
        world_seed,
        &config.world.generator,
    )));
    if let Ok(mut manager) = plugin_manager.lock() {
        manager.enable_plugins(PluginLoadOrder::PostWorld, &mut command_system);
    } else {
        warn!("Plugin manager lock is poisoned before POSTWORLD enable; plugins are disabled.");
    }
    let mut auto_save_counter: u32 = 0;
    // Compteur pour le scan périodique de visibilité d'entités. Tourne à 5 Hz
    // (toutes les 20 server ticks à 100 TPS) pour capter les transitions
    // entrée/sortie de vue des entités stationnaires quand un joueur se
    // déplace. Les entités mobiles sont déjà gérées par leur MovementUpdate.
    let mut entity_visibility_scan_counter: u32 = 0;
    let (console_tx, mut console_rx) = tokio::sync::mpsc::unbounded_channel::<String>();
    let console_tx_stdin = console_tx.clone();
    tokio::spawn(async move {
        let mut lines = BufReader::new(tokio::io::stdin()).lines();
        loop {
            match lines.next_line().await {
                Ok(Some(line)) => {
                    let trimmed = line.trim();
                    if trimmed.is_empty() {
                        continue;
                    }
                    if console_tx_stdin.send(trimmed.to_string()).is_err() {
                        break;
                    }
                }
                Ok(None) => {
                    info!("Local console input closed; server will continue running.");
                    break;
                }
                Err(error) => {
                    warn!(
                        "Local console input stopped after a read error: {}. Server will continue running.",
                        error
                    );
                    break;
                }
            }
        }
    });

    // Session tick interval (100 TPS = 10ms)
    let mut tick_timer = interval(Duration::from_millis(config.server.tick_rate));
    // CRITIQUE : par défaut `interval` = MissedTickBehavior::Burst. Si un tick
    // dépasse `tick_rate` (ex: casser un bloc = chunk + item entity + envoi),
    // l'interval rattrape en RAFALE → dans le `tokio::select!`, l'arm
    // `tick_timer.tick()` devient toujours-prêt → l'arm `recv` n'est PLUS
    // jamais élu → input client gelé, ET les ticks rattrapés fast-forwardent
    // le cycle jour/nuit. `Skip` : on ne rejoue jamais les ticks manqués,
    // on reprend la cadence normale → pas de rafale, pas de famine recv,
    // pas de fast-forward du temps.
    tick_timer.set_missed_tick_behavior(MissedTickBehavior::Skip);
    let mut should_stop = false;
    let mut console_input_open = true;
    let mut webui_tps_tracker = mc_rs_webui::metrics::TpsTracker::new();
    let mut webui_snapshot_counter: u32 = 0;
    let mut webui_system_probe = mc_rs_webui::metrics::SystemProbe::new();
    // Ring-buffer push tous les 100 server ticks (~1 Hz à 100 TPS).
    let mut webui_history_counter: u32 = 0;

    // ── Web admin panel (mc-rs-webui) ──
    // Channels + snapshot partagés avec le crate webui. La main loop met à
    // jour le snapshot ~20 Hz, push les events+logs dans les broadcasts.
    let webui_snapshot = std::sync::Arc::new(tokio::sync::RwLock::new({
        let mut snap = mc_rs_webui::ServerSnapshot::default();
        snap.motd = config.server.motd.clone();
        snap.world_name = config.world.name.clone();
        snap.max_players = config.server.max_players;
        snap.gamemode = config.gameplay.gamemode_id();
        snap.difficulty = config.gameplay.difficulty_id();
        snap.boot_instant = Some(std::time::Instant::now());
        snap.uptime_start_unix = chrono::Utc::now().timestamp();
        snap
    }));

    let webui_task = if config.webui.enabled {
        let handle = mc_rs_webui::WebUiHandle::new(
            console_tx.clone(),
            webui_snapshot.clone(),
            webui_event_tx.clone(),
            webui_log_tx.clone(),
        );
        info!(
            "[webui] web admin panel enabled — http://{}",
            config.webui.bind
        );
        Some(mc_rs_webui::serve(handle, config.webui.clone()))
    } else {
        None
    };
    drop(webui_task); // detach — la tâche vit tant que le process tourne

    // ── Query Gamespy v4 (UDP) ──
    // query_protocol::start lance un thread bloquant qui lit `query_snapshot`
    // (std::sync, accessible depuis un thread non-tokio). La main loop met à
    // jour ce snapshot quand le ServerSnapshot webui change.
    let query_snapshot =
        std::sync::Arc::new(std::sync::RwLock::new(crate::query_protocol::QueryStatus {
            motd: config.server.motd.clone(),
            gametype: "SMP".to_string(),
            map: config.world.name.clone(),
            num_players: 0,
            max_players: config.server.max_players,
            host_port: config.server.port,
            host_ip: "0.0.0.0".to_string(),
            player_names: Vec::new(),
            plugins: String::new(),
            version: "1.26.20".to_string(),
        }));

    if config.query.enabled {
        let bind = format!("{}:{}", config.query.address, config.query.port);
        let snap_clone = query_snapshot.clone();
        let status_fn = move || {
            snap_clone.read().map(|s| s.clone()).unwrap_or_else(|_| {
                crate::query_protocol::QueryStatus {
                    motd: String::new(),
                    gametype: "SMP".into(),
                    map: String::new(),
                    num_players: 0,
                    max_players: 0,
                    host_port: 0,
                    host_ip: String::new(),
                    player_names: Vec::new(),
                    plugins: String::new(),
                    version: String::new(),
                }
            })
        };
        match crate::query_protocol::start(&bind, status_fn) {
            Ok(()) => info!("[query] listening on {}", bind),
            Err(e) => warn!("[query] failed to bind {}: {e}", bind),
        }
    }

    // ── RCON Source-format (TCP) ──
    // rcon::start tourne dans des threads std (TcpListener bloquant) ; on bridge
    // le std::mpsc::Receiver vers un tokio::sync::mpsc pour pouvoir l'attendre
    // dans le tokio::select! de la main loop.
    let mut rcon_rx: Option<tokio::sync::mpsc::UnboundedReceiver<crate::rcon::RconCommand>> = None;
    if config.rcon.enabled {
        if config.rcon.password.is_empty() {
            warn!("[rcon] enabled=true mais password vide — RCON désactivé pour sécurité");
        } else {
            let bind = format!("{}:{}", config.rcon.address, config.rcon.port);
            match crate::rcon::start(&bind, config.rcon.password.clone()) {
                Ok(std_rx) => {
                    let (tokio_tx, tokio_rx) = tokio::sync::mpsc::unbounded_channel();
                    std::thread::spawn(move || {
                        while let Ok(cmd) = std_rx.recv() {
                            if tokio_tx.send(cmd).is_err() {
                                break;
                            }
                        }
                    });
                    rcon_rx = Some(tokio_rx);
                }
                Err(e) => warn!("[rcon] failed to bind {}: {e}", bind),
            }
        }
    }

    loop {
        crate::watchdog::checkpoint(0); // loop-top
        if should_stop {
            info!("Server stopping...");
            if let Ok(mut manager) = plugin_manager.lock() {
                manager.disable_all(&mut command_system);
            } else {
                warn!("Plugin manager lock is poisoned during shutdown.");
            }
            // Save all dirty chunks
            crate::watchdog::checkpoint(13); // shutdown_save
            if let Ok(mut cache) = chunk_cache.lock() {
                cache.save_dirty();
            }
            // level.dat snapshot
            let level = crate::level_dat::LevelData {
                seed: world_seed,
                generator: config.world.generator.clone(),
                time: world_state.time,
                spawn_x: 0.5,
                spawn_y: 64.0,
                spawn_z: 0.5,
                do_daylight_cycle: world_state.do_daylight_cycle,
                do_weather_cycle: world_state.do_weather_cycle,
                is_raining: world_state.is_raining,
                is_thundering: world_state.is_thundering,
                last_played_unix: std::time::SystemTime::now()
                    .duration_since(std::time::UNIX_EPOCH)
                    .map(|d| d.as_secs())
                    .unwrap_or(0),
                world_name: config.world.name.clone(),
            };
            if let Err(e) = level.save(&world_dir) {
                warn!("level.dat save failed: {e}");
            } else {
                info!("level.dat saved");
            }
            // Save all connected players
            for (_, conn) in connections.iter() {
                if let Some(ref xuid) = conn.xuid {
                    let save = player_data::PlayerSaveData::from_runtime(
                        conn.position,
                        [conn.yaw, conn.pitch],
                        conn.gamemode,
                        20.0,
                        20.0,
                        conn.spawn_position,
                        &conn.inventory,
                    );
                    let _ = player_data::save_player(xuid, &save);
                }
            }
            info!("World and player data saved.");
            break;
        }
        tokio::select! {
            // Receive UDP packets (this awaits until data arrives)
            result = raknet.recv_and_process() => {
                crate::watchdog::checkpoint(1); // recv_and_process
                if !result {
                    continue;
                }

                // Accept new peers
                crate::watchdog::checkpoint(2); // accept_peers
                while let Some(peer) = raknet.accept() {
                    let addr = peer.addr;
                    info!("New peer: {}", addr);
                    let conn = Connection::new(
                        addr,
                        Arc::clone(&server_keypair),
                        Arc::clone(&chunk_cache),
                        Arc::clone(&conn_config),
                        server_state.persistent.world_spawn,
                        server_state.effective_default_gamemode(conn_config.default_gamemode),
                        server_state.effective_difficulty(conn_config.difficulty),
                        false,
                        Arc::clone(&event_manager),
                    );
                    connections.insert(addr, conn);
                    peers.insert(addr, peer);
                }

                // Process events from all peers
                crate::watchdog::checkpoint(3); // process_peer_events@recv
                process_peer_events(
                    &mut peers,
                    &mut connections,
                    &mut raknet,
                    &mut registry,
                    &mut item_entities,
                    &mut mob_entities,
                    &mut world_state,
                    &mut server_state,
                    &plugin_manager,
                    &command_system,
                    &chunk_cache,
                    &mut should_stop,
                    &event_manager,
                    &mut furnace_manager,
                );
            }

            // Tick sessions periodically
            _ = tick_timer.tick() => {
                // Heartbeat watchdog : bumpé ICI (et pas en haut de boucle) car
                // c'est le VRAI progrès du jeu. Si l'arm `recv` spin et affame
                // ce tick (bug Windows UDP CONNRESET), ou si une phase du tick
                // se bloque, le heartbeat gèle → watchdog déclenche.
                crate::watchdog::beat();
                crate::watchdog::checkpoint(4); // webui_snapshot / tick start
                let current_tps = webui_tps_tracker.on_tick();
                webui_snapshot_counter = webui_snapshot_counter.wrapping_add(1);

                // Snapshot update ~20 Hz (tous les 5 server ticks à 100 TPS).
                if webui_snapshot_counter % 5 == 0 {
                    let players_snap: Vec<mc_rs_webui::PlayerSnapshot> = registry
                        .players
                        .values()
                        .map(|p| mc_rs_webui::PlayerSnapshot {
                            addr: p.addr.to_string(),
                            name: p.name.clone(),
                            uuid: p.uuid,
                            xuid: p.xuid.clone(),
                            entity_id: p.entity_id as u64,
                            position: p.position,
                            yaw: p.yaw,
                            pitch: p.pitch,
                            head_yaw: p.head_yaw,
                            gamemode: p.gamemode,
                        })
                        .collect();
                    let chunks_loaded = chunk_cache.lock().map(|c| c.cached_count()).unwrap_or(0);
                    let world_time = world_state.time as i64;
                    let weather = if world_state.is_thundering {
                        "thunder"
                    } else if world_state.is_raining {
                        "rain"
                    } else {
                        "clear"
                    }
                    .to_string();
                    let item_count = item_entities.all().count() as u32;
                    let mob_count = mob_entities.all().count() as u32;
                    let passive_count = (_passive_entities.tnt.len()
                        + _passive_entities.falling_blocks.len()
                        + _passive_entities.xp_orbs.len())
                        as u32;
                    let sessions = raknet.session_count() as u32;
                    // Live values (peuvent changer via commandes /difficulty, /gamemode, etc.)
                    let live_difficulty = server_state
                        .persistent
                        .difficulty
                        .unwrap_or_else(|| config.gameplay.difficulty_id());
                    let live_gamemode = server_state
                        .persistent
                        .default_gamemode
                        .unwrap_or_else(|| config.gameplay.gamemode_id());
                    // Snapshot Query : reflète num_players + player_names temps réel.
                    if let Ok(mut qs) = query_snapshot.write() {
                        qs.num_players = players_snap.len() as u32;
                        qs.player_names = players_snap.iter().map(|p| p.name.clone()).collect();
                    }
                    if let Ok(mut snap) = webui_snapshot.try_write() {
                        snap.tps = current_tps;
                        snap.total_ticks = webui_tps_tracker.total_ticks();
                        snap.chunks_loaded = chunks_loaded;
                        snap.world_time = world_time;
                        snap.weather = weather;
                        snap.difficulty = live_difficulty;
                        snap.gamemode = live_gamemode;
                        snap.entities = mc_rs_webui::snapshot::EntityStats {
                            players: players_snap.len() as u32,
                            mobs: mob_count,
                            items: item_count,
                            passive: passive_count,
                        };
                        snap.net.active_sessions = sessions;
                        snap.players = players_snap;
                    }
                }

                // Push history rings ~1 Hz (tous les 100 server ticks à 100 TPS).
                webui_history_counter = webui_history_counter.wrapping_add(1);
                if webui_history_counter % 100 == 0 {
                    let sys = webui_system_probe.sample();
                    let now_unix = chrono::Utc::now().timestamp();
                    if let Ok(mut snap) = webui_snapshot.try_write() {
                        snap.system = sys;
                        // Collecte toutes les valeurs dans des locaux avant d'emprunter
                        // les rings mutablement (borrow checker).
                        let v_tps = snap.tps;
                        let v_players = snap.players.len() as f32;
                        let v_chunks = snap.chunks_loaded as f32;
                        let v_mem = snap.system.mem_mb;
                        let v_cpu = snap.system.cpu_percent;
                        let v_bi = snap.net.bytes_in_per_sec as f32;
                        let v_bo = snap.net.bytes_out_per_sec as f32;
                        let v_ent = (snap.entities.mobs
                            + snap.entities.items
                            + snap.entities.passive
                            + snap.entities.players) as f32;
                        snap.history_tps.push(v_tps, now_unix);
                        snap.history_players.push(v_players, now_unix);
                        snap.history_chunks.push(v_chunks, now_unix);
                        snap.history_mem_mb.push(v_mem, now_unix);
                        snap.history_cpu_percent.push(v_cpu, now_unix);
                        snap.history_bytes_in_per_sec.push(v_bi, now_unix);
                        snap.history_bytes_out_per_sec.push(v_bo, now_unix);
                        snap.history_entities_total.push(v_ent, now_unix);
                    }
                }

                crate::watchdog::checkpoint(5); // raknet.tick_sessions
                raknet.tick_sessions().await;

                crate::watchdog::checkpoint(6); // world_tick
                // World tick (day/night cycle, weather)
                let world_packets = world_state.tick();
                for wp in world_packets {
                    match wp {
                        WorldPacket::SetTime(time) => {
                            let time_bytes = encode_set_time(time);
                            for (addr, conn) in connections.iter_mut() {
                                if conn.is_in_game() {
                                    let pkt = conn.encode_compressed_packet(
                                        packet_id::SET_TIME,
                                        &time_bytes,
                                    );
                                    let prepared = conn.prepare_for_send(pkt);
                                    raknet.send_to_session(addr, prepared, Reliability::ReliableOrdered, false);
                                }
                            }
                        }
                    }
                }

                crate::watchdog::checkpoint(7); // game_tick
                // Game tick (20 TPS = 1 game tick / 5 server ticks).
                // Met à jour : combat i-frames, hunger drain/regen, attribute desync sync.
                let mut world_gametick_fired = false;
                for (addr, conn) in connections.iter_mut() {
                    if !conn.is_in_game() {
                        continue;
                    }
                    conn.game_tick_accum = conn.game_tick_accum.saturating_add(1);
                    if conn.game_tick_accum >= 5 {
                        conn.game_tick_accum = 0;
                        world_gametick_fired = true;
                        for pkt in conn.tick_game_state() {
                            let prepared = conn.prepare_for_send(pkt);
                            raknet.send_to_session(
                                addr,
                                prepared,
                                Reliability::ReliableOrdered,
                                false,
                            );
                        }
                    }
                }

                // Furnace tick (20 TPS, partagé — une seule passe par game tick
                // quel que soit le nombre de joueurs). Les furnaces enregistrés
                // burn leur fuel + cook leur input. Les résultats (completed /
                // xp_to_give) sont loggés pour l'instant ; la vraie notif UI au
                // joueur ayant la fenêtre ouverte sera branchée quand la UI
                // furnace complète sera implémentée.
                // Process pending BlockActorData updates (sign edit / etc.) :
                //   - Décode NBT, persiste dans SignManager
                //   - Broadcast aux autres joueurs en réémettant le packet.
                let mut pending_block_actor: Vec<(std::net::SocketAddr, crate::connection::PendingBlockActorUpdate)> = Vec::new();
                for (addr, conn) in connections.iter_mut() {
                    let updates = std::mem::take(&mut conn.pending_block_actor_updates);
                    for u in updates {
                        pending_block_actor.push((*addr, u));
                    }
                }
                for (sender_addr, upd) in pending_block_actor {
                    // Persist sign data si le NBT est un sign valide.
                    if let Some(sign_data) = crate::sign_storage::parse_sign_nbt(&upd.nbt) {
                        info!(
                            "[{}] Sign edit at {:?}: front={:?} back={:?}",
                            sender_addr, upd.position, sign_data.front.text, sign_data.back.text
                        );
                        sign_manager.set(upd.position, sign_data);
                    }
                    // Broadcast à tous les joueurs (y compris l'éditeur pour
                    // confirmation server-authoritative).
                    let mut writer = mc_rs_proto::io::ProtoWriter::with_capacity(upd.nbt.len() + 12);
                    writer.write_var_i32(upd.position.0);
                    writer.write_var_i32(upd.position.1);
                    writer.write_var_i32(upd.position.2);
                    writer.write_byte_array(&upd.nbt);
                    let payload = writer.into_bytes();
                    for (addr, conn) in connections.iter_mut() {
                        if !conn.is_in_game() {
                            continue;
                        }
                        let bytes = conn
                            .encode_compressed_packet(packet_id::BLOCK_ACTOR_DATA, &payload);
                        let prepared = conn.prepare_for_send(bytes);
                        raknet.send_to_session(addr, prepared, Reliability::ReliableOrdered, true);
                    }
                }

                // Process pending block UI opens (crafting table, anvil,
                // enchanting table, furnace). Envoie ContainerOpen avec le
                // window_type approprié.
                for (addr, conn) in connections.iter_mut() {
                    let Some(ui_open) = conn.pending_block_ui_open.take() else {
                        continue;
                    };
                    let (window_type, pos) = match ui_open {
                        crate::connection::PendingBlockUiOpen::CraftingTable { pos } => {
                            (1i8, pos)
                        }
                        crate::connection::PendingBlockUiOpen::Anvil { pos } => (5i8, pos),
                        crate::connection::PendingBlockUiOpen::Enchanting { pos } => (3i8, pos),
                        crate::connection::PendingBlockUiOpen::Furnace { pos } => (2i8, pos),
                    };
                    let window_id: u8 = 60 + (window_type as u8 & 0x0F);
                    let open_pkt = mc_rs_proto::packets::world::ContainerOpen {
                        window_id,
                        window_type: window_type as u8,
                        position: [pos.0, pos.1, pos.2],
                        actor_unique_id: -1,
                    };
                    let bytes = conn.encode_compressed_packet(
                        packet_id::CONTAINER_OPEN,
                        &open_pkt.encode(),
                    );
                    let prepared = conn.prepare_for_send(bytes);
                    raknet.send_to_session(addr, prepared, Reliability::ReliableOrdered, true);
                    tracing::info!(
                        "[{}] Opened block UI type={} at {:?}",
                        addr, window_type, pos
                    );
                }

                // Process pending chest opens (broadcast ContainerOpen +
                // InventoryContent pour les 27 slots du chest cliqué).
                for (addr, conn) in connections.iter_mut() {
                    let Some((cx, cy, cz)) = conn.pending_chest_open.take() else {
                        continue;
                    };
                    let pos = (cx, cy, cz);
                    chest_manager.add_viewer(pos);
                    let data = chest_manager.get_or_create(pos).clone();
                    // Window ID dynamique (1-100 plage block container).
                    let window_id: u8 = 50;
                    // Register BlockContainer dans l'InventoryManager du joueur :
                    // associe windowId=50 → InvKey::BlockContainer pour que
                    // les ItemStackRequest soient routés correctement.
                    conn.inventory_manager.associate_block_container(window_id);
                    // Pré-remplit les 27 slots du joueur avec les items du
                    // chest pour que les transactions liront les bons items.
                    for (i, src) in data.slots.iter().enumerate() {
                        if let Some(dest) = conn.inventory.block_container.get_mut(i) {
                            *dest = mc_rs_proto::packets::player::ItemStackWrapper::legacy(
                                src.clone(),
                            );
                        }
                    }
                    conn.open_chest_pos = Some(pos);
                    let open_pkt = mc_rs_proto::packets::world::ContainerOpen {
                        window_id,
                        window_type: 0, // CONTAINER (chest)
                        position: [cx, cy, cz],
                        actor_unique_id: -1,
                    };
                    let open_bytes = conn
                        .encode_compressed_packet(packet_id::CONTAINER_OPEN, &open_pkt.encode());
                    let prepared = conn.prepare_for_send(open_bytes);
                    raknet.send_to_session(addr, prepared, Reliability::ReliableOrdered, true);
                    // InventoryContent : 27 slots du chest.
                    let mut content_writer = mc_rs_proto::io::ProtoWriter::with_capacity(64);
                    content_writer.write_var_u32(window_id as u32);
                    content_writer.write_var_u32(data.slots.len() as u32);
                    for slot in &data.slots {
                        let wrapper = mc_rs_proto::packets::player::ItemStackWrapper::legacy(
                            slot.clone(),
                        );
                        wrapper.encode(&mut content_writer);
                    }
                    // FullContainerName + storage stack id
                    content_writer.write_u8(0); // container_name_id
                    content_writer.write_bool(false); // dynamic_id
                    content_writer.write_var_i32(0); // storage_stack_id
                    let bytes = conn.encode_compressed_packet(
                        packet_id::INVENTORY_CONTENT,
                        content_writer.as_bytes(),
                    );
                    let prepared = conn.prepare_for_send(bytes);
                    raknet.send_to_session(addr, prepared, Reliability::ReliableOrdered, true);
                    tracing::info!(
                        "[{}] Opened chest at ({},{},{}) — viewers={}, slots={}",
                        addr,
                        cx,
                        cy,
                        cz,
                        chest_manager
                            .get(pos)
                            .map(|d| d.viewers)
                            .unwrap_or(0),
                        data.slots.len()
                    );
                }

                // Sync des modifications de chest entre InventoryManager
                // et ChestManager partagé. Si le joueur déplace un item du
                // chest vers son inventaire (et vice-versa), set_slot
                // (InvKey::BlockContainer) push dans pending_block_container_writes.
                for conn in connections.values_mut() {
                    let writes = conn.inventory_manager.drain_block_container_writes();
                    if writes.is_empty() {
                        continue;
                    }
                    let Some(pos) = conn.open_chest_pos else {
                        continue;
                    };
                    for (slot, item) in writes {
                        chest_manager.set_slot(pos, slot, item);
                    }
                }

                // Tick Lua plugin scheduler chaque server tick (100 TPS).
                if let Ok(mut manager) = plugin_manager.lock() {
                    manager.tick_scheduler();
                }

                if world_gametick_fired {
                    let results = furnace_manager.tick_all(&crafting_manager);
                    for ((x, y, z), r) in results {
                        if r.completed {
                            tracing::debug!(
                                "Furnace at ({x}, {y}, {z}) finished cooking (+{:.1} xp)",
                                r.xp_to_give
                            );
                        }
                    }

                    // Spawner naturel mob — utilise spawn_rules_vanilla.
                    // is_night : world_time entre 13000 et 23000 (PMMP convention).
                    let world_time = world_state.time.rem_euclid(24000);
                    let is_night = (13000..23000).contains(&world_time);
                    if let Ok(mut cache) = chunk_cache.lock() {
                        let mut rng = rand::thread_rng();
                        crate::mob_spawner::tick(
                            &mut rng,
                            &registry,
                            &mut cache,
                            &mut mob_entities,
                            is_night,
                        );
                    }
                }

                // Tick-based chunk sending (rate limited, spiral order)
                for (addr, conn) in connections.iter_mut() {
                    if conn.should_stream_chunks() {
                        let chunk_responses = conn.send_queued_chunks();
                        for resp in chunk_responses {
                            let prepared = conn.prepare_for_send(resp);
                            raknet.send_to_session(addr, prepared, Reliability::ReliableOrdered, false);
                        }
                    }
                }

                crate::watchdog::checkpoint(10); // item_tick
                let mut item_tick_result = if let Ok(mut cache) = chunk_cache.lock() {
                    item_entities.tick(&registry, &mut cache)
                } else {
                    crate::item_entities::TickResult {
                        despawned: Vec::new(),
                        pickup_candidates: Vec::new(),
                        movement_updates: Vec::new(),
                    }
                };
                for update in item_tick_result.movement_updates.drain(..) {
                    broadcast_entity_movement_culled(
                        &mut connections,
                        &mut raknet,
                        &update.add_packet,
                        packet_id::ADD_ITEM_ACTOR,
                        &update.move_packet,
                        &update.motion_packet,
                        update.entity_unique_id,
                        update.entity_position,
                    );
                }

                for entity in item_tick_result.despawned {
                    let remove_bytes = entity.remove_packet();
                    broadcast_entity_remove_culled(
                        &mut connections,
                        &mut raknet,
                        entity.entity_unique_id,
                        &remove_bytes,
                    );
                }

                for pickup in item_tick_result.pickup_candidates {
                    let Some(entity) = item_entities
                        .all()
                        .find(|entity| entity.entity_runtime_id == pickup.entity_runtime_id)
                        .cloned()
                    else {
                        continue;
                    };

                    let collected = if let Some(conn) = connections.get_mut(&pickup.player_addr) {
                        // PMMP `Inventory::addItem()` via le manager — déclenche
                        // le listener (track + pending_sync) pour chaque slot
                        // modifié. Le sync wire est ensuite émis par
                        // `tick_inventory_flush()`.
                        let added = conn
                            .inventory_manager
                            .add_item_to_main(&mut conn.inventory, entity.item.clone());
                        if added {
                            let sync_pkts: Vec<Vec<u8>> = conn
                                .tick_inventory_flush()
                                .into_iter()
                                .map(|p| conn.prepare_for_send(p))
                                .collect();
                            Some((conn.entity_runtime_id, sync_pkts))
                        } else {
                            None
                        }
                    } else {
                        None
                    };

                    let Some((collector_runtime_id, sync_packets)) = collected else {
                        continue;
                    };

                    let Some(removed_entity) = item_entities.remove(pickup.entity_runtime_id) else {
                        continue;
                    };

                    info!(
                        "[{}] Picked up item entity {} (item_id={})",
                        pickup.player_addr,
                        removed_entity.entity_runtime_id,
                        removed_entity.item.id,
                    );

                    for packet in sync_packets {
                        raknet.send_to_session(
                            &pickup.player_addr,
                            packet,
                            Reliability::ReliableOrdered,
                            true,
                        );
                    }

                    let take_bytes = TakeItemActor {
                        item_actor_runtime_id: removed_entity.entity_runtime_id,
                        taker_actor_runtime_id: collector_runtime_id,
                    }
                    .encode();
                    let remove_bytes = removed_entity.remove_packet();

                    // Culling : seuls les joueurs qui voyaient l'item entity
                    // doivent recevoir TakeItemActor + Remove. Pour les autres,
                    // l'entity_id leur est inconnu, donc le client ignorerait
                    // ces paquets (ou pire, génèrerait un warning).
                    for (addr, conn) in connections.iter_mut() {
                        if !conn.is_in_game() {
                            continue;
                        }
                        if !conn.visible_entities.remove(&removed_entity.entity_unique_id) {
                            continue;
                        }
                        let take_pkt = conn.encode_compressed_packet(
                            packet_id::TAKE_ITEM_ACTOR,
                            &take_bytes,
                        );
                        let take_prepared = conn.prepare_for_send(take_pkt);
                        raknet.send_to_session(
                            addr,
                            take_prepared,
                            Reliability::ReliableOrdered,
                            true,
                        );

                        let remove_pkt = conn.encode_compressed_packet(
                            packet_id::REMOVE_ACTOR,
                            &remove_bytes,
                        );
                        let remove_prepared = conn.prepare_for_send(remove_pkt);
                        raknet.send_to_session(
                            addr,
                            remove_prepared,
                            Reliability::ReliableOrdered,
                            true,
                        );
                    }
                }

                crate::watchdog::checkpoint(9); // mob_tick
                // Fix deadlock : on NE tient PAS le guard `chunk_cache` pendant
                // les envois réseau (raknet.send_to_session). On collecte le
                // résultat du tick sous lock, on relâche le guard, PUIS on
                // émet les paquets. Tenir un std::sync::Mutex pendant un appel
                // réseau potentiellement bloquant est une cause de gel.
                let mob_tick_result = if let Ok(mut cache) = chunk_cache.lock() {
                    Some(mob_entities.tick(&mut cache))
                } else {
                    None
                };
                if let Some(tick_result) = mob_tick_result {
                    for update in tick_result.movement_updates {
                        broadcast_entity_movement_culled(
                            &mut connections,
                            &mut raknet,
                            &update.add_packet,
                            packet_id::ADD_ACTOR,
                            &update.move_packet,
                            &update.motion_packet,
                            update.entity_unique_id,
                            update.entity_position,
                        );
                    }
                }

                entity_visibility_scan_counter += 1;
                if entity_visibility_scan_counter >= 20 {
                    entity_visibility_scan_counter = 0;
                    entity_visibility_scan(
                        &mut connections,
                        &mut raknet,
                        &item_entities,
                        &mob_entities,
                    );
                }

                crate::watchdog::checkpoint(11); // autosave
                // Auto-save every 1500 ticks (~15 s at 100 TPS). Raccourci de
                // 30000→1500 car save_chunk_now par-édition a été retiré
                // (flush LevelDB synchrone sous guard = hazard de gel) : on
                // s'appuie maintenant uniquement sur le dirty-tracking +
                // autosave batché pour la persistance.
                auto_save_counter += 1;
                if server_state.auto_save_enabled && auto_save_counter >= 1500 {
                    auto_save_counter = 0;
                    if let Ok(mut cache) = chunk_cache.lock() {
                        cache.save_dirty();
                    }
                }

                crate::watchdog::checkpoint(12); // process_peer_events@tick
                // Also check for events after session ticks
                process_peer_events(
                    &mut peers,
                    &mut connections,
                    &mut raknet,
                    &mut registry,
                    &mut item_entities,
                    &mut mob_entities,
                    &mut world_state,
                    &mut server_state,
                    &plugin_manager,
                    &command_system,
                    &chunk_cache,
                    &mut should_stop,
                    &event_manager,
                    &mut furnace_manager,
                );
            }

            console_line = console_rx.recv(), if console_input_open => {
                match console_line {
                    Some(line) => {
                        dispatch_command_line(
                            CommandSource::Console,
                            &line,
                            &command_system,
                            &mut connections,
                            &mut peers,
                            &mut raknet,
                            &mut registry,
                            &mut item_entities,
                            &mut mob_entities,
                            &mut world_state,
                            &mut server_state,
                            &plugin_manager,
                            &chunk_cache,
                            &mut should_stop,
                        );
                    }
                    None => {
                        console_input_open = false;
                    }
                }
            }

            rcon_cmd = async {
                match rcon_rx.as_mut() {
                    Some(rx) => rx.recv().await,
                    None => std::future::pending().await,
                }
            }, if rcon_rx.is_some() => {
                if let Some(cmd) = rcon_cmd {
                    info!("[rcon] {} -> {}", cmd.addr, cmd.command);
                    let output = dispatch_command_line(
                        CommandSource::Rcon,
                        &cmd.command,
                        &command_system,
                        &mut connections,
                        &mut peers,
                        &mut raknet,
                        &mut registry,
                        &mut item_entities,
                        &mut mob_entities,
                        &mut world_state,
                        &mut server_state,
                        &plugin_manager,
                        &chunk_cache,
                        &mut should_stop,
                    );
                    let response = output.join("\n");
                    let _ = cmd.response_tx.send(response);
                }
            }
        }
    }
}

fn spawn_and_broadcast_item_entity(
    log_context: &str,
    connections: &mut HashMap<SocketAddr, Connection>,
    raknet: &mut RakNetServer,
    item_entities: &mut ItemEntityManager,
    spawn: PendingItemEntitySpawn,
) {
    let entity = item_entities.spawn(spawn);
    let add_item_bytes = entity.add_actor_packet();
    info!(
        "[{}] AddItemActor entity prepared: {}",
        log_context,
        entity.debug_summary()
    );
    info!(
        "[{}] AddItemActor body: len={} hex={}",
        log_context,
        add_item_bytes.len(),
        hex_preview(&add_item_bytes, 96)
    );

    let entity_unique_id = entity.entity_unique_id;
    let entity_position = entity.position;
    for (other_addr, other_conn) in connections.iter_mut() {
        if !other_conn.is_in_game() {
            continue;
        }
        // Culling : on n'envoie l'AddItemActor qu'aux joueurs qui ont l'entité
        // dans leur rayon de vue. Si hors vue, on ne marque rien — un scan
        // périodique fera entrer l'entité dans la vue plus tard si le joueur
        // s'en approche.
        if !entity_culling::is_within_view_for(other_conn, entity_position) {
            continue;
        }
        other_conn.visible_entities.insert(entity_unique_id);
        let pkt = other_conn.encode_compressed_packet(packet_id::ADD_ITEM_ACTOR, &add_item_bytes);
        info!(
            "[{}] Sending ADD_ITEM_ACTOR to {}: compressed_len={} body_len={}",
            log_context,
            other_addr,
            pkt.len(),
            add_item_bytes.len()
        );
        let prepared = other_conn.prepare_for_send(pkt);
        raknet.send_to_session(other_addr, prepared, Reliability::ReliableOrdered, true);
    }
}

/// Broadcast Move+Motion d'une entité aux joueurs in_game, avec culling :
///
/// - StillHidden : skip
/// - JustEntered : envoie Add (avec `add_packet_id`) puis Move+Motion
/// - StillVisible : envoie Move+Motion
/// - JustLeft : envoie RemoveActor (entity sortie du rayon de vue)
///
/// Shared batch encoding : les 3 paquets potentiels (Add/Move/Motion) sont
/// encodés UNE SEULE FOIS via `encode_shared_batch` avec Zlib, puis clonés
/// par recipient avant `prepare_for_send` (qui applique l'encryption par-conn).
/// Économise N appels à zlib pour un broadcast à N joueurs.
#[allow(clippy::too_many_arguments)]
fn broadcast_entity_movement_culled(
    connections: &mut HashMap<SocketAddr, Connection>,
    raknet: &mut RakNetServer,
    add_packet: &[u8],
    add_packet_id: u32,
    move_packet: &[u8],
    motion_packet: &[u8],
    entity_unique_id: i64,
    entity_position: [f32; 3],
) {
    let shared_add = crate::connection::encode_shared_batch(
        add_packet_id,
        add_packet,
        mc_rs_proto::batch::CompressionAlgorithm::Zlib,
    );
    let shared_move = crate::connection::encode_shared_batch(
        packet_id::MOVE_ACTOR_ABSOLUTE,
        move_packet,
        mc_rs_proto::batch::CompressionAlgorithm::Zlib,
    );
    let shared_motion = crate::connection::encode_shared_batch(
        packet_id::SET_ACTOR_MOTION,
        motion_packet,
        mc_rs_proto::batch::CompressionAlgorithm::Zlib,
    );
    // Remove batch encodé en lazy : cas JustLeft est rare.
    let mut shared_remove: Option<Vec<u8>> = None;

    for (addr, conn) in connections.iter_mut() {
        if !conn.is_in_game() {
            continue;
        }
        let trans = entity_culling::classify_transition(
            &mut conn.visible_entities,
            entity_unique_id,
            entity_position,
            conn.position,
            conn.view_distance,
        );
        match trans {
            entity_culling::VisibilityTransition::StillHidden => continue,
            entity_culling::VisibilityTransition::JustLeft => {
                let remove_batch = shared_remove.get_or_insert_with(|| {
                    let remove_bytes =
                        mc_rs_proto::packets::player::RemoveEntity { entity_unique_id }.encode();
                    crate::connection::encode_shared_batch(
                        packet_id::REMOVE_ACTOR,
                        &remove_bytes,
                        mc_rs_proto::batch::CompressionAlgorithm::Zlib,
                    )
                });
                let prepared = conn.prepare_for_send(remove_batch.clone());
                raknet.send_to_session(addr, prepared, Reliability::ReliableOrdered, true);
                continue;
            }
            entity_culling::VisibilityTransition::JustEntered => {
                let prepared = conn.prepare_for_send(shared_add.clone());
                raknet.send_to_session(addr, prepared, Reliability::ReliableOrdered, true);
            }
            entity_culling::VisibilityTransition::StillVisible => {}
        }
        let move_prepared = conn.prepare_for_send(shared_move.clone());
        raknet.send_to_session(addr, move_prepared, Reliability::ReliableOrdered, false);
        let motion_prepared = conn.prepare_for_send(shared_motion.clone());
        raknet.send_to_session(addr, motion_prepared, Reliability::ReliableOrdered, false);
    }
}

/// Broadcast RemoveActor à tous les joueurs qui voyaient l'entité. Les autres
/// n'ont jamais reçu d'Add, donc le Remove serait un no-op côté client.
///
/// Shared batch encoding : encode une seule fois avec Zlib, clone par recipient.
fn broadcast_entity_remove_culled(
    connections: &mut HashMap<SocketAddr, Connection>,
    raknet: &mut RakNetServer,
    entity_unique_id: i64,
    remove_bytes: &[u8],
) {
    let shared = crate::connection::encode_shared_batch(
        packet_id::REMOVE_ACTOR,
        remove_bytes,
        mc_rs_proto::batch::CompressionAlgorithm::Zlib,
    );
    for (addr, conn) in connections.iter_mut() {
        if !conn.is_in_game() {
            continue;
        }
        if !conn.visible_entities.remove(&entity_unique_id) {
            continue;
        }
        let prepared = conn.prepare_for_send(shared.clone());
        raknet.send_to_session(addr, prepared, Reliability::ReliableOrdered, true);
    }
}

/// Scan périodique de visibilité d'entités. Capture les transitions
/// entrée/sortie de vue pour les entités stationnaires quand un joueur se
/// déplace — les entités qui bougent sont déjà gérées par leur MovementUpdate.
///
/// Pour chaque (joueur, entité), `classify_transition` met à jour
/// `visible_entities` et indique si on doit envoyer Add (JustEntered) ou
/// Remove (JustLeft). Les autres cas (StillHidden, StillVisible) ne génèrent
/// aucun trafic — c'est tout l'intérêt du culling.
fn entity_visibility_scan(
    connections: &mut HashMap<SocketAddr, Connection>,
    raknet: &mut RakNetServer,
    item_entities: &crate::item_entities::ItemEntityManager,
    mob_entities: &crate::mob_entities::MobEntityManager,
) {
    // Snapshot des (id, position, shared_add_batch). Le shared_add_batch est
    // le résultat de `encode_shared_batch` — pré-compressé une seule fois pour
    // tous les joueurs qui le recevront via prepare_for_send (qui n'applique
    // que l'encryption par-conn).
    let item_snapshot: Vec<(i64, [f32; 3], Vec<u8>)> = item_entities
        .all()
        .map(|e| {
            let add = e.add_actor_packet();
            let shared = crate::connection::encode_shared_batch(
                packet_id::ADD_ITEM_ACTOR,
                &add,
                mc_rs_proto::batch::CompressionAlgorithm::Zlib,
            );
            (e.entity_unique_id, e.position, shared)
        })
        .collect();
    let mob_snapshot: Vec<(i64, [f32; 3], Vec<u8>)> = mob_entities
        .all()
        .map(|e| {
            let add = e.add_actor_packet();
            let shared = crate::connection::encode_shared_batch(
                packet_id::ADD_ACTOR,
                &add,
                mc_rs_proto::batch::CompressionAlgorithm::Zlib,
            );
            (e.base.entity_unique_id, e.base.position, shared)
        })
        .collect();

    for (addr, conn) in connections.iter_mut() {
        if !conn.is_in_game() {
            continue;
        }
        scan_for_player(raknet, addr, conn, &item_snapshot);
        scan_for_player(raknet, addr, conn, &mob_snapshot);
    }
}

fn scan_for_player(
    raknet: &mut RakNetServer,
    addr: &SocketAddr,
    conn: &mut Connection,
    entities: &[(i64, [f32; 3], Vec<u8>)],
) {
    for (entity_id, entity_pos, shared_add) in entities {
        let trans = entity_culling::classify_transition(
            &mut conn.visible_entities,
            *entity_id,
            *entity_pos,
            conn.position,
            conn.view_distance,
        );
        match trans {
            entity_culling::VisibilityTransition::StillHidden
            | entity_culling::VisibilityTransition::StillVisible => continue,
            entity_culling::VisibilityTransition::JustEntered => {
                let prepared = conn.prepare_for_send(shared_add.clone());
                raknet.send_to_session(addr, prepared, Reliability::ReliableOrdered, true);
            }
            entity_culling::VisibilityTransition::JustLeft => {
                let remove_bytes = mc_rs_proto::packets::player::RemoveEntity {
                    entity_unique_id: *entity_id,
                }
                .encode();
                let pkt = conn.encode_compressed_packet(packet_id::REMOVE_ACTOR, &remove_bytes);
                let prepared = conn.prepare_for_send(pkt);
                raknet.send_to_session(addr, prepared, Reliability::ReliableOrdered, true);
            }
        }
    }
}

#[allow(clippy::too_many_arguments)]
fn process_peer_events(
    peers: &mut HashMap<SocketAddr, mc_rs_raknet::RakNetPeer>,
    connections: &mut HashMap<SocketAddr, Connection>,
    raknet: &mut RakNetServer,
    registry: &mut PlayerRegistry,
    item_entities: &mut ItemEntityManager,
    mob_entities: &mut MobEntityManager,
    world_state: &mut WorldState,
    server_state: &mut ServerState,
    plugin_manager: &Arc<Mutex<PluginManager>>,
    command_system: &ServerCommandSystem,
    chunk_cache: &std::sync::Arc<std::sync::Mutex<ChunkCache>>,
    should_stop: &mut bool,
    event_manager: &Arc<std::sync::Mutex<crate::event::EventManager>>,
    furnace_manager: &mut crate::furnace::FurnaceManager,
) {
    let addrs: Vec<SocketAddr> = peers.keys().copied().collect();
    for addr in addrs {
        let (pending_events, receiver_disconnected) = {
            let Some(peer) = peers.get_mut(&addr) else {
                continue;
            };
            let mut pending_events = Vec::new();
            let receiver_disconnected = loop {
                match peer.event_rx.try_recv() {
                    Ok(event) => pending_events.push(event),
                    Err(tokio::sync::mpsc::error::TryRecvError::Empty) => break false,
                    Err(tokio::sync::mpsc::error::TryRecvError::Disconnected) => break true,
                }
            };
            (pending_events, receiver_disconnected)
        };

        for event in pending_events {
            match event {
                SessionEvent::Connected => {
                    info!("[{}] RakNet session fully connected", addr);
                }
                SessionEvent::Packet(data) => {
                    // Extract data from connection (scoped borrow)
                    let (
                        responses,
                        broadcasts,
                        join_info,
                        pending_commands,
                        item_spawns,
                        pending_entity_attacks,
                        pending_furnace_events,
                    ) = {
                        let Some(conn) = connections.get_mut(&addr) else {
                            continue;
                        };
                        let was_in_game = conn.is_in_game();

                        let responses = conn.handle_raw_batch(&data);
                        let responses: Vec<Vec<u8>> = responses
                            .into_iter()
                            .map(|r| conn.prepare_for_send(r))
                            .collect();

                        let join_info = if !was_in_game && conn.is_in_game() {
                            Some((
                                conn.display_name.clone().unwrap_or_default(),
                                conn.uuid.map(|u| *u.as_bytes()).unwrap_or([0u8; 16]),
                                conn.xuid.clone().unwrap_or_default(),
                                conn.entity_runtime_id,
                                conn.position,
                            ))
                        } else {
                            None
                        };

                        registry.update_position(
                            &addr,
                            conn.position,
                            conn.pitch,
                            conn.yaw,
                            conn.head_yaw,
                        );

                        let broadcasts = conn.take_broadcasts();
                        let pending_commands = conn.take_pending_commands();
                        let item_spawns = std::mem::take(&mut conn.pending_item_spawns);
                        let pending_entity_attacks = conn.take_pending_entity_attacks();
                        let pending_furnace_events = conn.take_pending_furnace_events();

                        (
                            responses,
                            broadcasts,
                            join_info,
                            pending_commands,
                            item_spawns,
                            pending_entity_attacks,
                            pending_furnace_events,
                        )
                    };
                    // Borrow of conn dropped here

                    // Send responses to this player
                    for response in responses {
                        raknet.send_to_session(&addr, response, Reliability::ReliableOrdered, true);
                    }

                    // If player just joined, broadcast to others
                    if let Some((name, uuid, xuid, runtime_id, position)) = join_info {
                        let entity_id = runtime_id as i64;

                        let player_gamemode =
                            connections.get(&addr).map(|c| c.gamemode).unwrap_or(0);
                        let is_op = server_state.is_op(&name);
                        if let Some(connection) = connections.get_mut(&addr) {
                            connection.is_op = is_op;
                        }
                        registry.players.insert(
                            addr,
                            crate::player_registry::PlayerInfo {
                                addr,
                                name: name.clone(),
                                uuid,
                                xuid: xuid.clone(),
                                entity_id,
                                position,
                                pitch: 0.0,
                                yaw: 0.0,
                                head_yaw: 0.0,
                                gamemode: player_gamemode,
                            },
                        );

                        let add_player_bytes = AddPlayer {
                            uuid,
                            username: name.clone(),
                            runtime_entity_id: runtime_id,
                            platform_chat_id: String::new(),
                            position,
                            velocity: [0.0, 0.0, 0.0],
                            pitch: 0.0,
                            yaw: 0.0,
                            head_yaw: 0.0,
                            gamemode: player_gamemode,
                            entity_unique_id: entity_id,
                            permission_level: if is_op { 2 } else { 1 },
                            command_permission: if is_op { 1 } else { 0 },
                        }
                        .encode();

                        let player_skin = connections
                            .get(&addr)
                            .and_then(|c| c.skin.as_ref().map(|s| s.to_serialized(&xuid)))
                            .unwrap_or_default();
                        let player_list_add = PlayerList {
                            action: 0,
                            entries: vec![PlayerListAdd {
                                uuid,
                                entity_id,
                                username: name.clone(),
                                xuid: xuid.clone(),
                                platform_chat_id: String::new(),
                                build_platform: 0,
                                skin: player_skin,
                                is_teacher: false,
                                is_host: false,
                                is_subclient: false,
                            }],
                        }
                        .encode();

                        // Don't broadcast AddPlayer for spectators (they're invisible)
                        for (other_addr, other_conn) in connections.iter_mut() {
                            if *other_addr != addr {
                                // Always send PlayerList (needed for tab list)
                                let pkt = other_conn.encode_compressed_packet(
                                    packet_id::PLAYER_LIST,
                                    &player_list_add,
                                );
                                let prepared = other_conn.prepare_for_send(pkt);
                                raknet.send_to_session(
                                    other_addr,
                                    prepared,
                                    Reliability::ReliableOrdered,
                                    true,
                                );

                                // Only send AddPlayer if NOT spectator
                                if player_gamemode != 3 {
                                    let pkt = other_conn.encode_compressed_packet(
                                        packet_id::ADD_PLAYER,
                                        &add_player_bytes,
                                    );
                                    let prepared = other_conn.prepare_for_send(pkt);
                                    raknet.send_to_session(
                                        other_addr,
                                        prepared,
                                        Reliability::ReliableOrdered,
                                        true,
                                    );
                                }
                            }
                        }

                        info!(
                            "[{}] {} joined the game (entity_id={})",
                            addr, name, entity_id
                        );

                        // PMMP `PlayerJoinEvent`. Fire pour les plugins.
                        if let Ok(mut ev_mgr) = event_manager.lock() {
                            let mut ev = crate::event::player::PlayerJoinEvent {
                                player_addr: addr,
                                display_name: name.clone(),
                                xuid: xuid.clone(),
                                entity_runtime_id: runtime_id,
                                position,
                                gamemode: player_gamemode,
                                join_message: format!("{} joined the game", name),
                            };
                            ev_mgr.call(&mut ev);
                        }

                        // Au join : envoyer Add seulement pour les entités
                        // dans le rayon de vue du nouveau joueur. Le scan
                        // périodique gérera l'entrée des autres entités si le
                        // joueur se déplace.
                        if let Some(joined_conn) = connections.get_mut(&addr) {
                            for entity in item_entities.all() {
                                if !entity_culling::is_within_view_for(joined_conn, entity.position)
                                {
                                    continue;
                                }
                                joined_conn.visible_entities.insert(entity.entity_unique_id);
                                let pkt = joined_conn.encode_compressed_packet(
                                    packet_id::ADD_ITEM_ACTOR,
                                    &entity.add_actor_packet(),
                                );
                                let prepared = joined_conn.prepare_for_send(pkt);
                                raknet.send_to_session(
                                    &addr,
                                    prepared,
                                    Reliability::ReliableOrdered,
                                    true,
                                );
                            }
                            for entity in mob_entities.all() {
                                if !entity_culling::is_within_view_for(
                                    joined_conn,
                                    entity.base.position,
                                ) {
                                    continue;
                                }
                                joined_conn
                                    .visible_entities
                                    .insert(entity.base.entity_unique_id);
                                let pkt = joined_conn.encode_compressed_packet(
                                    packet_id::ADD_ACTOR,
                                    &entity.add_actor_packet(),
                                );
                                let prepared = joined_conn.prepare_for_send(pkt);
                                raknet.send_to_session(
                                    &addr,
                                    prepared,
                                    Reliability::ReliableOrdered,
                                    true,
                                );
                            }
                        }

                        let mut command_runtime = ExecutionContext::new(
                            CommandSource::Console,
                            command_system,
                            connections,
                            peers,
                            raknet,
                            registry,
                            item_entities,
                            mob_entities,
                            world_state,
                            server_state,
                            plugin_manager,
                            chunk_cache,
                            should_stop,
                        );
                        command_runtime.sync_available_commands_for_all();
                    }

                    // Broadcast packets to all OTHER connections.
                    // Multi-packet batching : tous les broadcasts du tick d'un même
                    // joueur source sont coalescés en UN seul batch par algo, puis
                    // prepare_for_send (encryption per-player) à chaque destinataire.
                    // Pré-calcule les batches Zlib/Snappy/None à la demande.
                    // Culling par distance : si le joueur source est hors du rayon de
                    // vue d'un destinataire, on saute tous les broadcasts de ce tick
                    // (move/set_actor_data/block break sont liés à sa position).
                    let source_pos = connections.get(&addr).map(|c| c.position);
                    if !broadcasts.is_empty() {
                        let mut batch_zlib: Option<Vec<u8>> = None;
                        let mut batch_snappy: Option<Vec<u8>> = None;
                        let mut batch_none: Option<Vec<u8>> = None;
                        let build_batch = |algo: mc_rs_proto::batch::CompressionAlgorithm| {
                            let pkts: Vec<Vec<u8>> = broadcasts
                                .iter()
                                .map(|(id, payload)| {
                                    mc_rs_proto::codec::encode_packet(*id, payload)
                                })
                                .collect();
                            let batch_payload = mc_rs_proto::batch::encode_batch(&pkts, algo, 1);
                            let mut result = Vec::with_capacity(1 + batch_payload.len());
                            result.push(0xFE);
                            result.extend_from_slice(&batch_payload);
                            result
                        };
                        for (other_addr, other_conn) in connections.iter_mut() {
                            if *other_addr == addr {
                                continue;
                            }
                            if let Some(spos) = source_pos {
                                let radius = entity_culling::entity_view_radius_blocks(
                                    other_conn.view_distance,
                                );
                                if entity_culling::dist_sq_xz(spos, other_conn.position)
                                    > radius * radius
                                {
                                    continue;
                                }
                            }
                            let shared = match other_conn.compression_algo {
                                mc_rs_proto::batch::CompressionAlgorithm::Zlib => batch_zlib
                                    .get_or_insert_with(|| {
                                        build_batch(mc_rs_proto::batch::CompressionAlgorithm::Zlib)
                                    })
                                    .clone(),
                                mc_rs_proto::batch::CompressionAlgorithm::Snappy => batch_snappy
                                    .get_or_insert_with(|| {
                                        build_batch(
                                            mc_rs_proto::batch::CompressionAlgorithm::Snappy,
                                        )
                                    })
                                    .clone(),
                                mc_rs_proto::batch::CompressionAlgorithm::None => batch_none
                                    .get_or_insert_with(|| {
                                        build_batch(mc_rs_proto::batch::CompressionAlgorithm::None)
                                    })
                                    .clone(),
                            };
                            let prepared = other_conn.prepare_for_send(shared);
                            raknet.send_to_session(
                                other_addr,
                                prepared,
                                Reliability::ReliableOrdered,
                                true,
                            );
                        }
                    }

                    for command in pending_commands {
                        if !connections.contains_key(&addr) {
                            break;
                        }
                        dispatch_command_line(
                            CommandSource::Player(addr),
                            &command,
                            command_system,
                            connections,
                            peers,
                            raknet,
                            registry,
                            item_entities,
                            mob_entities,
                            world_state,
                            server_state,
                            plugin_manager,
                            chunk_cache,
                            should_stop,
                        );
                    }

                    let log_context = addr.to_string();
                    for spawn in item_spawns {
                        spawn_and_broadcast_item_entity(
                            &log_context,
                            connections,
                            raknet,
                            item_entities,
                            spawn,
                        );
                    }

                    // Apply furnace register/unregister events queued par Connection
                    // lors des place/break de blocs furnace/blast_furnace/smoker.
                    for ev in pending_furnace_events {
                        match ev {
                            crate::connection::PendingFurnaceEvent::Register { pos, kind } => {
                                furnace_manager.register(pos, kind);
                                tracing::info!(
                                    "[{}] Furnace registered at {:?} kind={:?}",
                                    addr,
                                    pos,
                                    kind
                                );
                            }
                            crate::connection::PendingFurnaceEvent::Unregister { pos } => {
                                if furnace_manager.unregister(pos).is_some() {
                                    tracing::info!("[{}] Furnace unregistered at {:?}", addr, pos);
                                }
                            }
                        }
                    }

                    for attack in pending_entity_attacks {
                        const ACTION_ATTACK: u32 = 1;
                        if attack.action_type != ACTION_ATTACK {
                            continue;
                        }

                        // Si la target est un autre joueur → combat PvP via combat::attack_entity.
                        let target_player_addr = connections
                            .iter()
                            .find(|(other_addr, c)| {
                                **other_addr != addr
                                    && c.entity_runtime_id == attack.target_runtime_id
                                    && c.is_in_game()
                            })
                            .map(|(a, _)| *a);

                        if let Some(tgt_addr) = target_player_addr {
                            // Récupère la position de l'attaquant (sera utilisée pour knockback).
                            let attacker_pos = connections
                                .get(&addr)
                                .map(|c| c.position)
                                .unwrap_or([0.0, 0.0, 0.0]);
                            // Calcule dégât de base depuis held item (durability::base_attack_points) + 1 main nue.
                            let base_damage = connections
                                .get(&addr)
                                .and_then(|c| {
                                    let held = &c.inventory.slots[c.inventory.held_slot as usize];
                                    crate::durability::durable_info(held.item.id)
                                        .map(|i| i.tier.base_attack_points() as f32)
                                })
                                .unwrap_or(1.0);

                            // Appliquer l'attaque sur la target.
                            let outcome_info =
                                if let Some(target_conn) = connections.get_mut(&tgt_addr) {
                                    let outcome = {
                                        let events = target_conn.events.clone();
                                        let mut ev = events.lock().unwrap();
                                        crate::combat::attack_entity(
                                            &mut *ev,
                                            target_conn.entity_runtime_id,
                                            target_conn.position,
                                            &mut target_conn.attributes,
                                            &mut target_conn.combat,
                                            crate::event::entity::DamageCause::EntityAttack,
                                            base_damage,
                                            Some(attack.target_runtime_id),
                                            Some(attacker_pos),
                                            crate::combat::DEFAULT_KNOCKBACK_FORCE,
                                        )
                                    };
                                    info!(
                                        "[{}] PvP attack on {}: {} damage, died={}",
                                        addr,
                                        target_conn.entity_runtime_id,
                                        outcome.applied_damage,
                                        outcome.died,
                                    );
                                    Some((
                                        target_conn.entity_runtime_id,
                                        target_conn.position,
                                        outcome.knockback,
                                        outcome.died,
                                        outcome.applied_damage > 0.0,
                                        target_conn.spawn_position,
                                    ))
                                } else {
                                    None
                                };

                            if let Some((target_rid, target_pos, kb, died, hit, target_spawn)) =
                                outcome_info
                            {
                                // Hurt animation broadcast à tous les viewers.
                                if hit && !died {
                                    let hurt_bytes =
                                        crate::combat_packets::hurt_animation(target_rid);
                                    for (other_addr, other_conn) in connections.iter_mut() {
                                        if other_conn.is_in_game() {
                                            let pkt = other_conn.encode_compressed_packet(
                                                packet_id::ACTOR_EVENT,
                                                &hurt_bytes,
                                            );
                                            let prep = other_conn.prepare_for_send(pkt);
                                            raknet.send_to_session(
                                                other_addr,
                                                prep,
                                                Reliability::ReliableOrdered,
                                                true,
                                            );
                                        }
                                    }
                                }

                                // Knockback motion → envoyé à la target.
                                if let Some((kx, ky, kz)) = kb {
                                    if let Some(tc) = connections.get_mut(&tgt_addr) {
                                        let tick = tc.tick;
                                        let bytes = crate::combat_packets::encode_set_actor_motion(
                                            target_rid,
                                            [kx, ky, kz],
                                            tick,
                                        );
                                        let pkt = tc.encode_compressed_packet(
                                            packet_id::SET_ACTOR_MOTION,
                                            &bytes,
                                        );
                                        let prep = tc.prepare_for_send(pkt);
                                        raknet.send_to_session(
                                            &tgt_addr,
                                            prep,
                                            Reliability::ReliableOrdered,
                                            false,
                                        );
                                    }
                                }

                                if died {
                                    // Death animation à tous + message broadcast.
                                    let death_bytes =
                                        crate::combat_packets::death_animation(target_rid);
                                    for (other_addr, other_conn) in connections.iter_mut() {
                                        if other_conn.is_in_game() {
                                            let pkt = other_conn.encode_compressed_packet(
                                                packet_id::ACTOR_EVENT,
                                                &death_bytes,
                                            );
                                            let prep = other_conn.prepare_for_send(pkt);
                                            raknet.send_to_session(
                                                other_addr,
                                                prep,
                                                Reliability::ReliableOrdered,
                                                true,
                                            );
                                        }
                                    }
                                    // Respawn packet envoyé à la target pour
                                    // l'autoriser à respawn (READY_TO_SPAWN=1).
                                    if let Some(tc) = connections.get_mut(&tgt_addr) {
                                        // Restore full HP pour le respawn.
                                        tc.attributes
                                            .must_get_mut(crate::attribute::ids::HEALTH)
                                            .set_value(20.0, true);
                                        tc.attributes
                                            .must_get_mut(crate::attribute::ids::HUNGER)
                                            .set_value(20.0, true);
                                        tc.combat = crate::combat::CombatState::new();
                                        tc.position = target_spawn;
                                        let respawn_bytes = crate::combat_packets::encode_respawn(
                                            target_spawn,
                                            crate::combat_packets::respawn_state::READY_TO_SPAWN,
                                            target_rid,
                                        );
                                        let pkt = tc.encode_compressed_packet(
                                            packet_id::RESPAWN,
                                            &respawn_bytes,
                                        );
                                        let prep = tc.prepare_for_send(pkt);
                                        raknet.send_to_session(
                                            &tgt_addr,
                                            prep,
                                            Reliability::ReliableOrdered,
                                            true,
                                        );
                                    }
                                }

                                // Ignore unused
                                let _ = target_pos;
                            }
                            continue;
                        }

                        if let Some(result) =
                            mob_entities.apply_attack(attack.target_runtime_id, 4.0)
                        {
                            let target_unique_id = attack.target_runtime_id as i64;
                            if let Some(update_bytes) = result.update_attributes_packet {
                                // Culling : un joueur qui ne voit pas le mob
                                // n'a pas besoin de ses UpdateAttributes.
                                for (other_addr, other_conn) in connections.iter_mut() {
                                    if !other_conn.is_in_game() {
                                        continue;
                                    }
                                    if !other_conn.visible_entities.contains(&target_unique_id) {
                                        continue;
                                    }
                                    let pkt = other_conn.encode_compressed_packet(
                                        packet_id::UPDATE_ATTRIBUTES,
                                        &update_bytes,
                                    );
                                    let prepared = other_conn.prepare_for_send(pkt);
                                    raknet.send_to_session(
                                        other_addr,
                                        prepared,
                                        Reliability::ReliableOrdered,
                                        true,
                                    );
                                }
                            }

                            if let Some(remove_bytes) = result.remove_packet {
                                broadcast_entity_remove_culled(
                                    connections,
                                    raknet,
                                    target_unique_id,
                                    &remove_bytes,
                                );
                            }

                            if let Some(death_position) = result.death_position {
                                let log_context = format!("{addr}:mob-death");
                                for drop in result.drops {
                                    spawn_and_broadcast_item_entity(
                                        &log_context,
                                        connections,
                                        raknet,
                                        item_entities,
                                        PendingItemEntitySpawn::with_scatter(drop, death_position),
                                    );
                                }
                            }
                        }
                    }
                }
                SessionEvent::Disconnected => {
                    // Save player data before removing
                    if let Some(conn) = connections.get(&addr) {
                        if let Some(ref xuid) = conn.xuid {
                            let save_data = player_data::PlayerSaveData::from_runtime(
                                conn.position,
                                [conn.yaw, conn.pitch],
                                conn.gamemode,
                                20.0,
                                20.0,
                                conn.spawn_position,
                                &conn.inventory,
                            );
                            if let Err(e) = player_data::save_player(xuid, &save_data) {
                                warn!("Failed to save player data: {}", e);
                            }
                        }
                    }

                    // Broadcast RemoveEntity + PlayerList(REMOVE) to all others
                    if let Some(player_info) = registry.remove(&addr) {
                        info!("[{}] {} left the game", addr, player_info.name);

                        // PMMP `PlayerQuitEvent` pour les plugins.
                        if let Ok(mut ev_mgr) = event_manager.lock() {
                            let mut ev = crate::event::player::PlayerQuitEvent {
                                player_addr: addr,
                                display_name: player_info.name.clone(),
                                xuid: player_info.xuid.clone(),
                                entity_runtime_id: player_info.entity_id as u64,
                                quit_message: format!("{} left the game", player_info.name),
                                quit_reason: "Client Disconnect".to_string(),
                            };
                            ev_mgr.call(&mut ev);
                        }

                        let remove_entity = RemoveEntity {
                            entity_unique_id: player_info.entity_id,
                        }
                        .encode();

                        let player_list_remove = PlayerList {
                            action: 1,
                            entries: vec![PlayerListAdd {
                                uuid: player_info.uuid,
                                entity_id: player_info.entity_id,
                                username: String::new(),
                                xuid: String::new(),
                                platform_chat_id: String::new(),
                                build_platform: 0,
                                skin: Default::default(),
                                is_teacher: false,
                                is_host: false,
                                is_subclient: false,
                            }],
                        }
                        .encode();

                        for (other_addr, other_conn) in connections.iter_mut() {
                            if *other_addr != addr {
                                let pkt = other_conn.encode_compressed_packet(
                                    packet_id::REMOVE_ACTOR,
                                    &remove_entity,
                                );
                                let prepared = other_conn.prepare_for_send(pkt);
                                raknet.send_to_session(
                                    other_addr,
                                    prepared,
                                    Reliability::ReliableOrdered,
                                    true,
                                );

                                let pkt = other_conn.encode_compressed_packet(
                                    packet_id::PLAYER_LIST,
                                    &player_list_remove,
                                );
                                let prepared = other_conn.prepare_for_send(pkt);
                                raknet.send_to_session(
                                    other_addr,
                                    prepared,
                                    Reliability::ReliableOrdered,
                                    true,
                                );
                            }
                        }
                        let mut command_runtime = ExecutionContext::new(
                            CommandSource::Console,
                            command_system,
                            connections,
                            peers,
                            raknet,
                            registry,
                            item_entities,
                            mob_entities,
                            world_state,
                            server_state,
                            plugin_manager,
                            chunk_cache,
                            should_stop,
                        );
                        command_runtime.sync_available_commands_for_all();
                    } else {
                        info!("[{}] Disconnected", addr);
                    }

                    connections.remove(&addr);
                    peers.remove(&addr);
                    break;
                }
            }
        }

        if receiver_disconnected && peers.contains_key(&addr) {
            if let Some(player_info) = registry.remove(&addr) {
                info!("[{}] {} connection lost", addr, player_info.name);
            }
            connections.remove(&addr);
            peers.remove(&addr);
        }
    }
}
