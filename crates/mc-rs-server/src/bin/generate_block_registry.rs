use std::collections::BTreeMap;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

fn default_input_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("data/canonical_block_states.nbt")
}

fn default_output_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("src/world/block_registry_data.rs")
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let mut args = env::args().skip(1);
    let input = args.next().map(PathBuf::from).unwrap_or_else(default_input_path);
    let output = args.next().map(PathBuf::from).unwrap_or_else(default_output_path);

    if args.next().is_some() {
        eprintln!(
            "usage: cargo run -p mc-rs-server --bin generate_block_registry -- [input_nbt] [output_rs]"
        );
        std::process::exit(2);
    }

    let data = fs::read(&input)?;
    let mut cursor = &data[..];
    let mut first_runtime_ids = BTreeMap::new();
    let mut total_states = 0u32;

    while !cursor.is_empty() {
        let root = mc_rs_nbt::read_nbt_network(&mut cursor)?;
        if let Some(mc_rs_nbt::tag::NbtTag::String(name)) = root.compound.get("name") {
            first_runtime_ids.entry(name.clone()).or_insert(total_states);
        }
        total_states += 1;
    }

    let mut out = String::new();
    writeln!(
        out,
        "// @generated by `cargo run -p mc-rs-server --bin generate_block_registry -- {}`",
        input.display()
    )?;
    writeln!(out, "// Total states: {total_states}")?;
    writeln!(out, "// Unique block names: {}", first_runtime_ids.len())?;
    writeln!(out)?;
    writeln!(
        out,
        "pub const BLOCK_NAME_TO_FIRST_RUNTIME_ID: &[(&str, u32)] = &["
    )?;
    for (name, runtime_id) in &first_runtime_ids {
        writeln!(out, "    ({name:?}, {runtime_id}),")?;
    }
    writeln!(out, "];")?;

    fs::write(&output, out)?;

    println!(
        "Wrote {} names / {} total states to {}",
        first_runtime_ids.len(),
        total_states,
        output.display()
    );

    Ok(())
}
